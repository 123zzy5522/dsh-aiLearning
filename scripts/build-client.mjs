/**
 * Build `client.js` (the browser bundle DSH serves) from `client/src/`.
 *
 * The plugin system loads a prebuilt bundle: `dsh.client` points at one file,
 * so the source must be bundled ahead of time. `client.js` is committed on
 * purpose — a `link:` install and a GitHub install must both work without a
 * build step on the user's machine. CI re-runs this and fails if the committed
 * bundle is stale.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entry = path.join(root, "client", "src", "index.js");
const outFile = path.join(root, "client.js");

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "cjs",
  platform: "browser",
  target: ["es2020"],
  // React is provided by the DSH shell through the loader's `require`.
  external: ["react"],
  legalComments: "none",
  logLevel: "warning",
});

const code = result.outputFiles[0].text;
const bundle = `/* Generated by scripts/build-client.mjs from client/src/. Do not edit by hand. */
window.__ModuleLoader__.load({
  id: "dsh-ailearn",
  factory(require) {
    const module = { exports: {} };
    (function (module, exports, require) {
${code}
    })(module, module.exports, require);
    return module.exports.default ?? module.exports;
  },
});
`;

fs.writeFileSync(outFile, bundle, "utf8");
console.log(`client.js: ${(Buffer.byteLength(bundle) / 1024).toFixed(1)} KB from client/src/index.js`);
